"""Генерация Pawn-инклуда (.inc) для нативов и форвардов плагина."""

from __future__ import annotations

from typing import Any


def _literal(code: str, value: Any) -> str:
    if code == "b":
        return "true" if value else "false"
    if code == "f":
        text = repr(float(value))
        return text if "." in text or "e" in text else text + ".0"
    if code == "s":
        return '"' + str(value).replace("^", "^^").replace('"', '^"') + '"'
    return str(int(value))


def _param(name: str, code: str, default: Any = None) -> str:
    if code == "f":
        text = f"Float:{name}"
    elif code == "b":
        text = f"bool:{name}"
    elif code == "s":
        text = f"const {name}[]"
    else:
        text = name
    if default is not None:
        text += f" = {_literal(code, default)}"
    return text


def _doc(text: str) -> list[str]:
    if not text.strip():
        return []
    return ["/**", *(f" * {line}".rstrip() for line in text.strip().splitlines()), " */"]


def render_include(plugin: str, title: str, natives: list[dict[str, Any]], forwards: list[dict[str, Any]]) -> str:
    guard = f"_{plugin}_included"
    out = [
        f'// {title}: natives and forwards of the amxpy plugin "{plugin}".',
        "// Generated by amxpyc - do not edit.",
        "",
        f"#if defined {guard}",
        "    #endinput",
        "#endif",
        f"#define {guard}",
        "",
        f"#pragma reqlib {plugin}",
        "",
    ]
    for native in natives:
        defaults = native.get("defaults", {})
        params = [_param(name, code, defaults.get(name)) for name, code in native["params"]]
        returns = native["returns"]
        if returns == "s":  # строка возвращается через буфер, результат — длина
            params += ["output[]", "maxlen"]
        tag = {"f": "Float:", "b": "bool:"}.get(returns, "")
        out += _doc(native.get("doc", ""))
        out += [f"native {tag}{native['name']}({', '.join(params)});", ""]
    for forward in forwards:
        params = [_param(name, code) for name, code in forward["params"]]
        out += [f"forward {forward['name']}({', '.join(params)});", ""]
    return "\n".join(out)
